-- Journalise les créations, modifications et suppressions réalisées sur les tables
-- applicatives publiques. Les valeurs à caractère privé sont masquées dans les instantanés.
CREATE TABLE IF NOT EXISTS public.application_audit_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id uuid,
  actor_email text,
  actor_phone text,
  action text NOT NULL CHECK (action IN ('create', 'update', 'delete')),
  table_name text NOT NULL,
  record_id text,
  changed_fields text[] NOT NULL DEFAULT '{}',
  old_data jsonb,
  new_data jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS application_audit_logs_created_idx
  ON public.application_audit_logs (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS application_audit_logs_actor_idx
  ON public.application_audit_logs (actor_id, created_at DESC);
CREATE INDEX IF NOT EXISTS application_audit_logs_table_idx
  ON public.application_audit_logs (table_name, created_at DESC);

ALTER TABLE public.admin_activity_logs
  ADD COLUMN IF NOT EXISTS actor_email text,
  ADD COLUMN IF NOT EXISTS actor_phone text,
  ADD COLUMN IF NOT EXISTS ip_address text;

UPDATE public.admin_activity_logs AS activity
SET actor_email = auth_user.email,
    actor_phone = auth_user.phone
FROM auth.users AS auth_user
WHERE activity.user_id = auth_user.id
  AND (activity.actor_email IS NULL OR activity.actor_phone IS NULL);

ALTER TABLE public.application_audit_logs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.application_audit_logs FROM anon, authenticated;
GRANT SELECT ON public.application_audit_logs TO authenticated;
GRANT SELECT, INSERT ON public.application_audit_logs TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.application_audit_logs_id_seq TO service_role;

DROP POLICY IF EXISTS "Admins can view application audit logs" ON public.application_audit_logs;
CREATE POLICY "Admins can view application audit logs"
  ON public.application_audit_logs FOR SELECT TO authenticated
  USING (public.is_admin());

CREATE OR REPLACE FUNCTION public.capture_application_audit_log()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth, pg_temp
AS $$
DECLARE
  v_actor_id uuid := auth.uid();
  v_actor_email text;
  v_actor_phone text;
  v_old jsonb;
  v_new jsonb;
  v_record jsonb;
  v_record_id text;
  v_action text;
  v_changed_fields text[];
  v_old_safe jsonb;
  v_new_safe jsonb;
BEGIN
  IF TG_OP = 'INSERT' THEN
    v_action := 'create';
    v_new := to_jsonb(NEW);
    v_record := v_new;
    SELECT coalesce(array_agg(key ORDER BY key), '{}') INTO v_changed_fields FROM jsonb_object_keys(v_new) AS keys(key);
  ELSIF TG_OP = 'UPDATE' THEN
    v_action := 'update';
    v_old := to_jsonb(OLD);
    v_new := to_jsonb(NEW);
    v_record := v_new;
    SELECT coalesce(array_agg(keys.key ORDER BY keys.key), '{}') INTO v_changed_fields
      FROM (SELECT key FROM jsonb_object_keys(v_old) AS old_keys(key) UNION SELECT key FROM jsonb_object_keys(v_new) AS new_keys(key)) AS keys
      WHERE v_old -> keys.key IS DISTINCT FROM v_new -> keys.key;
    IF cardinality(v_changed_fields) = 0 THEN RETURN NEW; END IF;
  ELSE
    v_action := 'delete';
    v_old := to_jsonb(OLD);
    v_record := v_old;
    SELECT coalesce(array_agg(key ORDER BY key), '{}') INTO v_changed_fields FROM jsonb_object_keys(v_old) AS keys(key);
  END IF;

  IF v_actor_id IS NULL AND TG_TABLE_NAME = 'profiles' AND v_action = 'create' THEN
    v_actor_id := nullif(v_record ->> 'id', '')::uuid;
  END IF;
  IF v_actor_id IS NOT NULL THEN
    SELECT email, phone INTO v_actor_email, v_actor_phone FROM auth.users WHERE id = v_actor_id;
  ELSE
    v_actor_email := 'Système / tâche serveur';
  END IF;
  IF v_actor_id IS NULL AND TG_TABLE_NAME = 'support_requests' THEN
    IF coalesce(v_record ->> 'contact', '') LIKE '%@%' THEN v_actor_email := v_record ->> 'contact';
    ELSE v_actor_phone := v_record ->> 'contact'; END IF;
  END IF;

  v_record_id := coalesce(v_record ->> 'id', v_record ->> 'user_id', v_record ->> 'profile_id', v_record ->> 'request_id');

  SELECT coalesce(jsonb_object_agg(key,
    CASE WHEN key ~* '(password|token|secret|api.?key|authorization|cookie|email|phone|contact|address|content|message|body|bio|description|note|avatar|photo|image|uri|url|location|birth|religion|expectation|ip|user.?agent|code|otp)'
      THEN '"[masqué]"'::jsonb ELSE value END
  ), '{}'::jsonb) INTO v_old_safe FROM jsonb_each(coalesce(v_old, '{}'::jsonb));
  SELECT coalesce(jsonb_object_agg(key,
    CASE WHEN key ~* '(password|token|secret|api.?key|authorization|cookie|email|phone|contact|address|content|message|body|bio|description|note|avatar|photo|image|uri|url|location|birth|religion|expectation|ip|user.?agent|code|otp)'
      THEN '"[masqué]"'::jsonb ELSE value END
  ), '{}'::jsonb) INTO v_new_safe FROM jsonb_each(coalesce(v_new, '{}'::jsonb));

  INSERT INTO public.application_audit_logs (actor_id, actor_email, actor_phone, action, table_name, record_id, changed_fields, old_data, new_data)
  VALUES (v_actor_id, v_actor_email, v_actor_phone, v_action, TG_TABLE_NAME, v_record_id, coalesce(v_changed_fields, '{}'),
    CASE WHEN v_action IN ('update', 'delete') THEN v_old_safe END,
    CASE WHEN v_action IN ('create', 'update') THEN v_new_safe END);

  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.capture_application_audit_log() FROM PUBLIC, anon, authenticated;

DO $$
DECLARE
  target_table record;
BEGIN
  FOR target_table IN
    SELECT c.oid::regclass AS table_ref, c.relname AS table_name
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public'
      AND c.relkind IN ('r', 'p')
      AND c.relname NOT IN ('application_audit_logs', 'admin_activity_logs', 'admin_team_access_logs', 'profile_visits', 'sara_usage_events', 'password_recovery_codes', 'account_sessions')
  LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS application_audit_trigger ON %s', target_table.table_ref);
    EXECUTE format('CREATE TRIGGER application_audit_trigger AFTER INSERT OR UPDATE OR DELETE ON %s FOR EACH ROW EXECUTE FUNCTION public.capture_application_audit_log()', target_table.table_ref);
  END LOOP;
END;
$$;

CREATE OR REPLACE VIEW public.application_complete_audit_logs
WITH (security_invoker = true)
AS
  SELECT 'mutation-' || id::text AS id, actor_id, actor_email, actor_phone, action, table_name, record_id, changed_fields, old_data, new_data, created_at
  FROM public.application_audit_logs
  UNION ALL
  SELECT 'login-' || id::text AS id, user_id AS actor_id, actor_email, actor_phone, 'login'::text AS action, 'Connexion'::text AS table_name,
    user_id::text AS record_id,
    ARRAY['ip_address','country','region','city','browser','operating_system','device','page']::text[] AS changed_fields,
    NULL::jsonb AS old_data,
    jsonb_build_object('Adresse IP', ip_address, 'Pays', country, 'Région', region, 'Ville estimée', city, 'Navigateur', browser, 'Système', operating_system, 'Appareil', device, 'Page', page) AS new_data,
    created_at
  FROM public.admin_activity_logs;

REVOKE ALL ON public.application_complete_audit_logs FROM anon;
GRANT SELECT ON public.application_complete_audit_logs TO authenticated;
