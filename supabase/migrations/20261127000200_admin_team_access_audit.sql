CREATE TABLE IF NOT EXISTS public.admin_team_access_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  actor_contact text NOT NULL,
  target_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  target_contact text NOT NULL,
  action text NOT NULL CHECK (action IN ('invited', 'role_assigned', 'role_changed', 'access_removed')),
  old_role text,
  new_role text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS admin_team_access_logs_created_idx
  ON public.admin_team_access_logs (created_at DESC);

ALTER TABLE public.admin_team_access_logs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.admin_team_access_logs FROM anon, authenticated;
GRANT SELECT ON public.admin_team_access_logs TO authenticated;
GRANT SELECT, INSERT ON public.admin_team_access_logs TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.admin_team_access_logs_id_seq TO service_role;

DROP POLICY IF EXISTS "Admins can view team access audit logs" ON public.admin_team_access_logs;
CREATE POLICY "Admins can view team access audit logs"
  ON public.admin_team_access_logs FOR SELECT TO authenticated
  USING (public.is_admin());
